"""Generate the "contract data" that every Vector implementation is tested against.

    python tools/generate_contract_data.py          # (re)write the files
    python tools/generate_contract_data.py --check  # verify the files are current

Files written into protocol/:
    vectors.json         packet and ground-frame test vectors (valid and invalid)
    vectors.h            the same vectors as a C header, for the firmware tests
    sample_flight.hex    one 36-byte ground frame per line (hex): a whole flight
    sample_flight.csv    the same flight, decoded, for humans and spreadsheets
    expected_stats.json  the flight summary the app must reproduce

Do not edit those files by hand. Change the generator (ask Claude first).
"""
from __future__ import annotations

import csv
import dataclasses
import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "sim"))

from flight_model import generate_flight  # noqa: E402
from flight_stats import compute_stats  # noqa: E402
from vector_packet import (  # noqa: E402
    PHASE_NAMES, GroundFrame, Packet, crc16_ccitt_false, encode, encode_ground_frame,
)

OUT = ROOT / "protocol"


def _fields(p: Packet) -> dict:
    return dataclasses.asdict(p)


def _flip_byte(data: bytes, index: int) -> bytes:
    b = bytearray(data)
    b[index] ^= 0xFF
    return bytes(b)


def build_vectors(frames: list[GroundFrame]) -> dict:
    by_seq = {f.packet.seq: f.packet for f in frames}
    first_of_phase = {}
    for f in frames:
        first_of_phase.setdefault(f.packet.phase, f.packet)

    valid = [
        ("pad_armed", "On the pad, armed, 3D fix, 12 satellites.", first_of_phase[0]),
        ("boost_no_fix", "During boost: GPS fix lost, last known position repeated.", first_of_phase[1]),
        ("coast_fix_regained", "Coasting after the GPS re-acquired.", by_seq[14]),
        ("apogee", "First packet in the apogee phase.", first_of_phase[3]),
        ("descent", "First packet under parachute.", first_of_phase[4]),
        ("landed", "First packet after landing.", first_of_phase[5]),
        ("max_values", "Largest value of every field that allows it.", Packet(
            rocket_id=65535, seq=65535, time_ms=4294967295,
            lat_e7=900000000, lon_e7=1800000000, gps_alt_cm=2147483647,
            baro_alt_cm=2147483647, vspeed_cms=32767, battery_mv=65535,
            sats=63, fix_type=3, phase=5, flags=255)),
        ("negative_values", "Southern and western hemisphere, below the pad, falling.", Packet(
            rocket_id=7, seq=1, time_ms=1000,
            lat_e7=-338688000, lon_e7=-1512093000, gps_alt_cm=-500,
            baro_alt_cm=-150, vspeed_cms=-2000, battery_mv=3700,
            sats=8, fix_type=1, phase=4, flags=2)),
    ]

    base = encode(first_of_phase[0])
    bad_version = encode(dataclasses.replace(first_of_phase[0], version=2))
    bad_phase = encode(dataclasses.replace(first_of_phase[0], phase=6))
    invalid = [
        ("too_short", "33 bytes: one byte missing.", base[:33], "bad_length"),
        ("too_long", "35 bytes: one byte too many.", base + b"\x00", "bad_length"),
        ("empty", "No bytes at all.", b"", "bad_length"),
        ("corrupted_payload", "One payload byte flipped, CRC left alone.", _flip_byte(base, 10), "bad_crc"),
        ("corrupted_crc", "CRC byte flipped.", _flip_byte(base, 33), "bad_crc"),
        ("unknown_version", "Valid CRC but version 2. Apps must reject it.", bad_version, "bad_version"),
        ("unknown_phase", "Valid CRC but phase 6. Apps must reject it.", bad_phase, "bad_phase"),
    ]

    ground = []
    for name, packet_name, rssi, snr in [
        ("ground_strong", "pad_armed", -42, 11),
        ("ground_weak", "descent", -118, -15),
        ("ground_extremes", "landed", -128, 127),
    ]:
        pkt = next(p for n, _, p in valid if n == packet_name)
        ground.append({
            "name": name, "packet": packet_name, "rssi_dbm": rssi, "snr_db": snr,
            "hex": encode_ground_frame(GroundFrame(pkt, rssi, snr)).hex(),
        })
    ground_invalid = [
        {"name": "ground_missing_radio_bytes", "hex": base.hex(), "error": "bad_length"},
        {"name": "ground_corrupted_packet", "hex": (_flip_byte(base, 10) + b"\x00\x00").hex(),
         "error": "bad_crc"},
    ]

    return {
        "about": "Generated by tools/generate_contract_data.py. Do not edit by hand.",
        "crc_check": {"input_ascii": "123456789", "crc16_ccitt_false": "0x%04X" % crc16_ccitt_false(b"123456789")},
        "valid": [{"name": n, "description": d, "fields": _fields(p), "hex": encode(p).hex()}
                  for n, d, p in valid],
        "invalid": [{"name": n, "description": d, "hex": b.hex(), "error": e}
                    for n, d, b, e in invalid],
        "ground_valid": ground,
        "ground_invalid": ground_invalid,
    }


def _c_u(v: int, bits: int) -> str:
    return f"{v}u" if bits == 32 else str(v)


def _c_bytes(hex_str: str) -> str:
    return ", ".join(f"0x{b:02x}" for b in bytes.fromhex(hex_str))


def build_c_header(vec: dict) -> str:
    out = [
        "/* Generated by tools/generate_contract_data.py. Do not edit by hand. */",
        "#ifndef VECTOR_VECTORS_H",
        "#define VECTOR_VECTORS_H",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#define VX_CRC_CHECK_VALUE 0x29B1",
        "",
        "typedef struct {",
        "  const char *name;",
        "  uint8_t version; uint16_t rocket_id; uint16_t seq; uint32_t time_ms;",
        "  int32_t lat_e7; int32_t lon_e7; int32_t gps_alt_cm; int32_t baro_alt_cm;",
        "  int16_t vspeed_cms; uint16_t battery_mv;",
        "  uint8_t sats; uint8_t fix_type; uint8_t phase; uint8_t flags;",
        "  uint8_t bytes[34];",
        "} VxVectorValid;",
        "",
        "typedef struct { const char *name; const char *error; size_t len; uint8_t bytes[40]; } VxVectorInvalid;",
        "typedef struct { const char *name; int8_t rssi_dbm; int8_t snr_db; uint8_t bytes[36]; } VxVectorGround;",
        "",
        "static const VxVectorValid VX_VALID[] = {",
    ]
    for v in vec["valid"]:
        f = v["fields"]
        out.append(
            f'  {{"{v["name"]}", {f["version"]}, {f["rocket_id"]}, {f["seq"]}, {_c_u(f["time_ms"], 32)}, '
            f'{f["lat_e7"]}, {f["lon_e7"]}, {f["gps_alt_cm"]}, {f["baro_alt_cm"]}, '
            f'{f["vspeed_cms"]}, {f["battery_mv"]}, {f["sats"]}, {f["fix_type"]}, {f["phase"]}, {f["flags"]}, '
            f'{{{_c_bytes(v["hex"])}}}}},')
    out += ["};", f"static const size_t VX_VALID_COUNT = {len(vec['valid'])};", "",
            "static const VxVectorInvalid VX_INVALID[] = {"]
    for v in vec["invalid"]:
        n = len(bytes.fromhex(v["hex"]))
        body = _c_bytes(v["hex"]) if n else "0"
        out.append(f'  {{"{v["name"]}", "{v["error"]}", {n}, {{{body}}}}},')
    out += ["};", f"static const size_t VX_INVALID_COUNT = {len(vec['invalid'])};", "",
            "static const VxVectorGround VX_GROUND[] = {"]
    for g in vec["ground_valid"]:
        out.append(f'  {{"{g["name"]}", {g["rssi_dbm"]}, {g["snr_db"]}, {{{_c_bytes(g["hex"])}}}}},')
    out += ["};", f"static const size_t VX_GROUND_COUNT = {len(vec['ground_valid'])};", "",
            "#endif", ""]
    return "\n".join(out)


def build_csv(frames: list[GroundFrame]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["seq", "time_ms", "rocket_id", "lat_deg", "lon_deg", "gps_alt_m", "baro_alt_m",
                "vspeed_ms", "battery_mv", "sats", "fix_type", "phase", "armed", "rssi_dbm", "snr_db"])
    for f in frames:
        p = f.packet
        w.writerow([p.seq, p.time_ms, p.rocket_id, f"{p.lat_e7 / 1e7:.7f}", f"{p.lon_e7 / 1e7:.7f}",
                    f"{p.gps_alt_cm / 100:.2f}", f"{p.baro_alt_cm / 100:.2f}", f"{p.vspeed_cms / 100:.2f}",
                    p.battery_mv, p.sats, p.fix_type, PHASE_NAMES[p.phase], int(p.armed),
                    f.rssi_dbm, f.snr_db])
    return buf.getvalue()


def build_all() -> dict[str, str]:
    frames = generate_flight()
    stats = compute_stats([f.packet for f in frames])
    vectors = build_vectors(frames)
    return {
        "vectors.json": json.dumps(vectors, indent=2) + "\n",
        "vectors.h": build_c_header(vectors),
        "sample_flight.hex": "".join(encode_ground_frame(f).hex() + "\n" for f in frames),
        "sample_flight.csv": build_csv(frames),
        "expected_stats.json": json.dumps({
            "about": "Generated by tools/generate_contract_data.py from sample_flight.hex. "
                     "The app must match each value within 0.1.",
            "stats": stats,
        }, indent=2) + "\n",
    }


def main() -> int:
    check = "--check" in sys.argv[1:]
    files = build_all()
    OUT.mkdir(exist_ok=True)
    stale = []
    for name, text in files.items():
        path = OUT / name
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
            print(f"wrote protocol/{name}")
    if check:
        if stale:
            print("OUT OF DATE: " + ", ".join(stale))
            print("Run: python tools/generate_contract_data.py")
            return 1
        print("contract data is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
